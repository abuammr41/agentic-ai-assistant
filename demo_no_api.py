"""
demo_no_api.py
---------------
A FAKE/SCRIPTED run of the agent — no API key needed. This hard-codes the
"thinking" steps a real agent would make (normally the LLM decides these
live) but runs the REAL tool functions for real results, so you can see the
full plan -> act -> observe -> repeat flow working before any API key is
added.

Run: python demo_no_api.py
"""

from agent import calculator, web_search, write_file

GOAL = "Research what an AI agent is, calculate 15% tip on a $240 bill, and save both findings to a report."

print(f"GOAL: {GOAL}\n")
print("=" * 70)

print("\n[agent] Step 1 - I need to research 'AI agent' first.")
print("[tool call] web_search(query='what is an AI agent')")
search_result = web_search("what is an AI agent")
print("[tool result]\n" + search_result[:400] + "\n")

print("[agent] Step 2 - Now I need to calculate the 15% tip on $240.")
print("[tool call] calculator(expression='240 * 0.15')")
tip_result = calculator("240 * 0.15")
print(f"[tool result] {tip_result}\n")

print("[agent] Step 3 - I have both pieces, saving a combined report.")
report = f"""# Agent Demo Report

## Research: What is an AI agent?
{search_result}

## Calculation: 15% tip on $240
${tip_result}

---
Generated by a scripted (no-API) demo run of agentic_ai_assistant.
"""
save_result = write_file("portfolio_sample/demo_report_output.md", report)
print(f"[tool result] {save_result}\n")

print("=" * 70)
print("[agent] Done. Both tasks completed and saved to portfolio_sample/demo_report_output.md")
print("\nNote: in the REAL agent.py, an LLM (Claude or Gemini) decides every")
print("one of the steps above on its own, live, based on the goal — this")
print("script just hard-codes that decision-making to demo the tools without")
print("needing an API key yet.")
